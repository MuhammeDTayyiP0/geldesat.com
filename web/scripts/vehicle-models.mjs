/**
 * Brand → model → trim trees for the TR classifieds catalog.
 * Array value = leaf models. Object value = model with child trims.
 */
function wrap(models) {
  return { __wrap: true, ...models };
}

function bmw(digit, parts) {
  return parts.map((p) => (/^[A-Za-z]/.test(p) ? p : `${digit}${p}`));
}

function mb(letter, codes) {
  return codes.map((c) => `${letter} ${c}`);
}

